/**
 * fal's retarget spoke: the wire shapes a `.toApi("fal")` mapping must produce,
 * reachable from outside this directory.
 *
 * **Type-only, deliberately.** Every export here is a type; the module emits no
 * JavaScript at all, so importing it costs a bundle nothing. That is what lets
 * a native provider's mapping table be *checked* against fal's published body
 * for the endpoint it names, without that provider's bundle gaining a byte of
 * fal — no schema, no catalog, no check battery, no id arrays.
 *
 * ## Why the spoke exists rather than a direct import
 *
 * Two rules meet here and only this file satisfies both
 * (`test/import-graph.test.ts`):
 *
 * - **A11** — `src/providers/fal/gen/**` is importable only from
 *   `src/providers/fal/**`. A `kling/fal-target.ts` reaching straight for
 *   `../fal/gen/video-wire.gen` breaks it.
 * - **Rule 6** — a provider module may reach another provider's directory only
 *   through its `interop.ts`. That basename is the whole allowance, and this is
 *   it.
 *
 * So the generated by-id maps are re-exported here under names that say what
 * they are for, and the mapping tables in `src/providers/<native>/fal-target.ts`
 * index them.
 *
 * ## What a mapping gets from indexing these
 *
 * `FalVideoBodyById["fal-ai/kling-video/v2.5-turbo/pro/text-to-video"]` is
 * fal's own published request body for that endpoint, generated from fal's
 * OpenAPI. A mapper declared to return it cannot invent a field, misspell one,
 * or miss a required one — which is the difference between a hand table that is
 * checked and a hand table that is hoped for. The endpoint id in the type and
 * the endpoint id in the URL are the same literal, so they cannot drift either.
 */

