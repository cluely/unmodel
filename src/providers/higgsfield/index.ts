/**
 * `unmodel/higgsfield` — Higgsfield (https://higgsfield.ai): its own image and
 * video models (Soul, Marketing Studio, Ads Studio, Cinema Studio, Genjutsu)
 * and the third-party ones it hosts (Seedance, Kling, Wan, MiniMax, LTX,
 * Recraft, Ideogram, …), behind one key and one URL template.
 *
 * Two routes, four addresses:
 *
 * | address | route | serves |
 * |---|---|---|
 * | `higgsfield.image` | `POST https://api.higgsfield.ai/{endpoint}` | every route that answers images |
 * | `higgsfield.imageEdit` | 〃 | the image routes that take a picture to edit (a view) |
 * | `higgsfield.video` | 〃 | every route that answers a video |
 * | `higgsfield.characterTrain` | `POST https://api.higgsfield.ai/v1/custom-references` | Soul ID training |
 *
 * The three generation addresses post a route's own flat body to that
 * route's own path. There is no `model` field: `endpoint` selects the path
 * and never reaches the wire, and `hf_webhook` becomes the query parameter
 * the API reads it from. They are separate addresses because what a caller is
 * doing differs, not because the wire does (`docs/decisions.md` §2 and §4);
 * they share one shape gate and one check battery, and `imageEdit` refuses
 * nothing its wide neighbour accepts except what is not an edit.
 *
 * Every route is served, the hosted third-party ones included (owner
 * decision, 2026-11-24). Everything per-route is generated by
 * `scripts/codegen-higgsfield.ts` from Higgsfield's own published per-route
 * documents, snapshotted under `data/higgsfield/`; `higgsfield.characterTrain`
 * is the one hand-typed body.
 *
 * The three generation addresses are also refs in `unmodel/image`,
 * `unmodel/image-edit` and `unmodel/video` (`higgsfield/<route id>`), through
 * the adapters on `unmodel/higgsfield/unified`; the rows those adapters read
 * are on `unmodel/higgsfield/values`. Neither is re-exported here.
 *
 * What comes back: `checkRequestStatus` reports a submitted or polled request
 * the way every provider's checker does. The URL builders, the status tuples
 * and the response types cover the rest of the lifecycle — poll, cancel,
 * delete, estimate, upload, the preset lists.
 *
 * ## What is NOT here, and why
 *
 * - **Webhook verification.** Deliveries are signed (Standard Webhooks:
 *   `webhook-id`, `webhook-timestamp`, `webhook-signature`), and unmodel ships
 *   the header names, `WebhookDelivery` and `HIGGSFIELD_WEBHOOK_STATUSES` but
 *   no verifier. `revana.verifyWebhook` exists because two recorded real
 *   deliveries settled how its secret becomes a key; there is no recorded
 *   Higgsfield delivery to pin the `whsec_` decoding or the two-signature
 *   rotation against. It needs one, in `test/fixtures/higgsfield/`.
 * - **A checker for a Soul ID character.** Its `failed` carries `fail_reason`,
 *   whose type Higgsfield does not publish.
 * - **The console's playground presets** (`workflows/*`). Each is a page over
 *   a model row, with no path of its own to POST to.
 * - **The two misspelled legacy paths** (`higgsfiled/genjutsu/…`). They still
 *   answer; unmodel types the documented spelling only, and
 *   `HIGGSFIELD_EXCLUDED` carries the reason a request naming one is given.
 * - **The Agent API** (`/v1/agent/sessions`). It is in Higgsfield's SDKs only,
 *   in no documentation page, and is not a generation body.
 * - **The legacy v1 surface** (`/v1/image2video/dop`, `/v1/speak/higgsfield`,
 *   `/v1/text2image/soul`, the `{ params, webhook }` envelope and
 *   `/v1/job-sets`). Only the JavaScript SDK's v1 client still names it.
 * - **Per-request headers as parameters.** `Idempotency-Key` and
 *   `Hf-Expires-After` are the caller's choice per submit; their names and
 *   bounds are exported, and unmodel sets neither.
 *
 * Revana resells six of these models — Soul, Soul 2, Soul Cinema, Marketing
 * Studio and the two Genjutsu workflows are also `revana.image` /
 * `revana.video` ids — through a different body, and unmodel keeps the two
 * apart on purpose (`docs/decisions.md` §1).
 *
 * Auth is `Authorization: Key <KEY_ID>:<KEY_SECRET>`; unmodel never touches
 * keys. **Not exercised against a live key**: every body, bound and price
 * here is Higgsfield's published contract, read 2026-11-24.
 */

