//   https://www.recraft.ai/docs/api-reference/endpoints   (param compatibility, per-route
//     model lists)
//   https://www.recraft.ai/docs/api-reference/agents      (one-page model table and the
//     per-family parameter matrix)
//   https://www.recraft.ai/docs/api-reference/pricing     (per-image API unit charges)
//   https://www.recraft.ai/docs/api-reference/appendix    (max prompt length, supported sizes)
//   https://www.recraft.ai/docs/api-reference/openapi.json (SECONDARY: the docs-generated
//     OpenAPI. Its `TransformModel` enum types `model` on every generation and transform
//     request and lists exactly the 32 ids below as of 2026-11-12. It is
//     "Generated by the Recraft docs from
//     https://external.api.recraft.ai/doc/spec/external-api.yaml and extended with … V4.1
//     Flash", so the backend yaml lacks the two Flash ids — never cite it alone for those.)
// Verified 2026-11-12.
//
// Pricing conversions (documented so the arithmetic never rots unexplained):
// - Recraft bills in pre-purchased API units: USD $1.00 = 1,000 API units
//   (https://www.recraft.ai/docs/api-reference/pricing). The pricing table
//   lists every generation charge in both USD and units per image; the USD
//   figures below are copied verbatim from that table (units = USD × 1000).
// - Image generation is billed per generated image, so a request with `n` > 1
//   costs `n` × the per-image rate.
//
// The "max prompt length" appendix caps live on `ModelLimit.characters`
// (10,000 characters for the V4/V4.1 line — "| V4.1, V4.1 Utility, V4.1 Flash,
// V4, V4 Styles, including all Pro and Vector variants | 10,000 |" — and 1,000
// for V2/V3); the generations validator enforces them against `prompt`.
// `limit.context: 0` marks these as non-token models so the pipeline skips
// context-window checks.

